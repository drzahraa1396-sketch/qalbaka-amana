# مولد رسائل تثقيف صحي مبسطة للمريض في برنامج "قلبك أمانة"

def _yes(value):
    return str(value).strip().lower() in {
        "نعم", "yes", "y", "true", "1", "مدخن", "مصاب", "موجود"
    }

def _num(value):
    try:
        return float(value)
    except (TypeError, ValueError):
        return None

def generate_health_education(
    age=None, bmi=None, sbp=None, dbp=None, smoking=None,
    diabetes=None, hypertension=None, chol_mgdl=None, ldl_mgdl=None,
    risk_pct=None, statin_needed=None, statin_intensity=None,
    statin_regimen=None, bp_treatment=None, dm_treatment=None,
    statin_given=None, aspirin_given=None, established_ascvd=None,
    ckd=None, next_followup=None, **kwargs
):
    """إنشاء رسالة تثقيف صحي عملية وقصيرة للمريض."""
    lines = [
        "❤️ نصائح مهمة لصحتك",
        "",
        "هذه النصائح تساعدك على حماية قلبك وصحتك. اتبع تعليمات الطبيب ولا توقف أي دواء من نفسك.",
        "",
        "🥗 الغذاء الصحي:",
        "• قلل الملح في الطعام، وابتعد قدر الإمكان عن المخللات والشيبسي والأطعمة كثيرة الملح.",
        "• قلل الدهون والمقليات والسمن والزبدة واللحوم الدسمة.",
        "• أكثر من الخضار والفاكهة، واختر الأطعمة الطازجة قدر الإمكان.",
        "• قلل المشروبات المحلاة والحلويات والسكريات.",
        "",
        "🚶 الحركة والنشاط:",
        "• حاول المشي أو ممارسة نشاط بدني لمدة 30 دقيقة يوميًا، 5 أيام في الأسبوع، حسب قدرتك وتعليمات الطبيب.",
        "• إذا كنت غير معتاد على الرياضة، ابدأ تدريجيًا.",
    ]

    bmi_v = _num(bmi)
    if bmi_v is not None and bmi_v >= 25:
        lines += [
            "",
            "⚖️ الوزن:",
            "• إذا كان وزنك زائدًا، حاول إنقاص الوزن تدريجيًا من خلال الغذاء الصحي والحركة.",
            "• تجنب الحميات القاسية، واطلب نصيحة الفريق الطبي إذا احتجت مساعدة.",
        ]

    sbp_v, dbp_v = _num(sbp), _num(dbp)
    bp_high = (sbp_v is not None and sbp_v >= 140) or (dbp_v is not None and dbp_v >= 90)
    if _yes(hypertension) or bp_high or _yes(bp_treatment):
        lines += [
            "",
            "🩺 ضغط الدم:",
            "• قِس ضغط الدم بانتظام حسب الخطة التي حددها الطبيب وسجل القراءات.",
            "• قلل الملح والتزم بالغذاء الصحي والحركة.",
            "• التزم بأدوية الضغط في مواعيدها، ولا توقف العلاج أو تغير الجرعة من نفسك.",
        ]
    else:
        lines += [
            "",
            "🩺 ضغط الدم:",
            "• احرص على قياس ضغط الدم ومتابعته بشكل دوري.",
        ]

    if _yes(diabetes) or _yes(dm_treatment):
        lines += [
            "",
            "🩸 سكر الدم:",
            "• قِس سكر الدم بانتظام حسب الخطة التي حددها الطبيب، وسجل القراءات.",
            "• قلل السكريات والحلويات والمشروبات المحلاة.",
            "• انتظم في مواعيد الوجبات والتزم بأدوية السكر كما وصفها الطبيب.",
            "• لا تغير جرعة دواء السكر أو توقفه من نفسك.",
        ]
    else:
        lines += [
            "",
            "🩸 السكر:",
            "• إذا طلب منك الطبيب متابعة سكر الدم، التزم بالقياسات والمواعيد المحددة.",
        ]

    chol_v, ldl_v = _num(chol_mgdl), _num(ldl_mgdl)
    high_lipid = (chol_v is not None and chol_v >= 200) or (ldl_v is not None and ldl_v >= 100)
    if high_lipid or _yes(statin_needed) or _yes(statin_given):
        lines += [
            "",
            "🧪 الكوليسترول والدهون:",
            "• قلل الدهون المشبعة والمقليات والسمن والزبدة واللحوم الدسمة.",
            "• اهتم بالغذاء الصحي والحركة.",
            "• إذا وصف لك الطبيب علاجًا للكوليسترول، خذه بانتظام ولا توقفه من نفسك.",
        ]
    else:
        lines += [
            "",
            "🧪 الكوليسترول والدهون:",
            "• حافظ على غذاء قليل الدهون والمقليات واهتم بالحركة.",
        ]

    if _yes(smoking):
        lines += [
            "",
            "🚭 التدخين:",
            "• حاول التوقف عن التدخين؛ الإقلاع عنه يساعد على تقليل خطر أمراض القلب والجلطات.",
            "• اطلب مساعدة الفريق الطبي إذا احتجت دعمًا للإقلاع.",
        ]
    else:
        lines += [
            "",
            "🚭 التدخين:",
            "• استمر في تجنب التدخين والتعرض لدخانه قدر الإمكان.",
        ]

    if _yes(established_ascvd) or _yes(ckd):
        lines += [
            "",
            "❤️ المتابعة:",
            "• احرص على الالتزام الدقيق بالأدوية والمواعيد والفحوصات التي حددها الطبيب.",
            "• لا توقف علاجك أو تغيره دون الرجوع للطبيب.",
        ]

    lines += ["", "📅 المتابعة:"]
    if next_followup:
        lines.append(f"• موعد المتابعة المسجل لك: {next_followup}. احرص على الحضور في الموعد أو تواصل مع الوحدة إذا تعذر الحضور.")
    else:
        lines.append("• احرص على المتابعة الدورية مع الطبيب والالتزام بالمواعيد المحددة لك.")

    lines += [
        "",
        "⚠️ هذه رسالة للتثقيف الصحي وليست تشخيصًا نهائيًا. القرار الطبي والعلاج النهائي يحددهما الطبيب.",
        "",
        "❤️ نتمنى لك دوام الصحة والعافية.",
    ]
    return "\n".join(lines)
